class PinyinToHanzi:
    """
    拼音→汉字转换器

    支持：
    - 单字查找
    - 双字词维特比解码
    """

    def __init__(self, user_dict: dict = None):
        """
        参数:
            user_dict: 用户自定义词库
                { "pinyin": ["汉字1", "汉字2", ...] }
        """
        self._pinyin_table = _BUILTIN_PINYIN_TABLE.copy()
        self._bigram = _BUILTIN_BIGRAM.copy()

        if user_dict:
            for pinyin, chars in user_dict.items():
                pinyin = pinyin.lower()
                if pinyin in self._pinyin_table:
                    # 插入到最前面（优先使用用户自定义）
                    existing = self._pinyin_table[pinyin]
                    for c in chars:
                        if c in existing:
                            existing.remove(c)
                    self._pinyin_table[pinyin] = chars + existing
                else:
                    self._pinyin_table[pinyin] = chars

    def get_characters(self, pinyin: str) -> List[str]:
        """获取拼音对应的汉字候选列表"""
        pinyin = pinyin.lower()
        return self._pinyin_table.get(pinyin, [])

    def has_pinyin(self, pinyin: str) -> bool:
        """检查拼音是否在词库中"""
        return pinyin.lower() in self._pinyin_table

    def decode(self, pinyin_list: List[str]) -> dict:
        """
        维特比解码：拼音序列 → 最优汉字序列

        使用双字词转移概率 + 单字频率。

        参数:
            pinyin_list: 拼音列表 ["wo3", "shi4", ...]

        返回:
        {
            "text": str,                # 解码文本
            "segments": [               # 逐字/词信息
                {"char": str, "pinyin": str, ...}
            ],
            "candidates": list[list[str]],  # 各位置候选
        }
        """
        # 去声调
        pinyin_clean = []
        for p in pinyin_list:
            # 移除末尾的数字
            base = p.rstrip("012345")
            pinyin_clean.append(base)

        n = len(pinyin_clean)
        if n == 0:
            return {"text": "", "segments": [], "candidates": []}

        # 提取各位置候选
        candidates = [self.get_characters(p) for p in pinyin_clean]

        if n == 1:
            chars = candidates[0]
            text = chars[0] if chars else ""
            return {
                "text": text,
                "segments": [{"char": text, "pinyin": pinyin_clean[0]}],
                "candidates": candidates,
            }

        # 维特比解码
        # dp[i][c] = 到位置 i 选择汉字 c 的最大概率
        vocab = [set(pos_cands) for pos_cands in candidates]

        # 构建转移概率（简化：bigram 权重）
        dp = []
        back = []

        # 初始化第一列
        first_vocab = list(vocab[0])
        dp.append({c: 1.0 for c in first_vocab})
        back.append({c: None for c in first_vocab})

        for i in range(1, n):
            current_vocab = list(vocab[i])
            prev_vocab = list(vocab[i - 1])

            dp_i = {}
            back_i = {}

            for c2 in current_vocab:
                best_score = 0.0
                best_c1 = prev_vocab[0] if prev_vocab else None

                for c1 in prev_vocab:
                    # 基本转移分
                    bigram_score = 1.0

                    # 检查 bigram
                    p1 = pinyin_clean[i - 1]
                    p2 = pinyin_clean[i]
                    bigram_key = (p1, p2)
                    if bigram_key in self._bigram:
                        expected_bigram = self._bigram[bigram_key]
                        if c1 + c2 == expected_bigram:
                            bigram_score = 5.0  # 匹配到常用词

                    score = dp[i - 1].get(c1, 0.0) * bigram_score

                    if score > best_score:
                        best_score = score
                        best_c1 = c1

                dp_i[c2] = best_score
                back_i[c2] = best_c1

            dp.append(dp_i)
            back.append(back_i)

        # 回溯
        last_vocab = list(vocab[-1])
        if not last_vocab:
            return {"text": "", "segments": [], "candidates": candidates}

        best_last = max(last_vocab, key=lambda c: dp[-1].get(c, 0.0))

        result_chars = [best_last]
        for i in range(n - 1, 0, -1):
            prev_char = back[i][result_chars[-1]]
            result_chars.append(prev_char)

        result_chars.reverse()

        text = "".join(result_chars)

        segments = [
            {"char": c, "pinyin": pinyin_clean[i], "pinyin_original": pinyin_list[i]}
            for i, c in enumerate(result_chars)
        ]

        return {
            "text": text,
            "segments": segments,
            "candidates": candidates,
        }
